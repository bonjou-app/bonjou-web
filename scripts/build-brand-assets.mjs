import { mkdir, writeFile } from "node:fs/promises";
import { Resvg } from "@resvg/resvg-js";
import mark from "../src/share/brandMark.json" with { type: "json" };

// The React mark and every export use the same approved geometry.
const publicDir = new URL("../public/", import.meta.url);
await mkdir(new URL("brand/", publicDir), { recursive: true });

function svg(avatar = false) {
  const viewBox = avatar ? mark.avatarViewBox : mark.viewBox;
  const [x, y, width, height] = viewBox.split(" ");
  const background = avatar
    ? `  <rect x="${x}" y="${y}" width="${width}" height="${height}" fill="${mark.background}"/>\n`
    : "";
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" width="1024" height="1024" fill="${mark.color}">\n  <!-- Generated by npm run generate:brand from src/share/brandMark.json. -->\n${background}  <path fill-rule="evenodd" d="${mark.path}"/>\n</svg>\n`;
}

const transparent = svg();
const avatar = svg(true);
for (const [name, source] of [
  ["brand/bonjou-mark.svg", transparent],
  ["brand/bonjou-avatar.svg", avatar],
  ["favicon.svg", transparent],
]) {
  await writeFile(new URL(name, publicDir), source);
}

for (const [name, size, source] of [
  ["favicon-16.png", 16, transparent],
  ["favicon-32.png", 32, transparent],
  ["apple-touch-icon.png", 180, avatar],
  ["brand/bonjou-icon-192.png", 192, avatar],
  ["brand/bonjou-avatar.png", 512, avatar],
  ["brand/bonjou-mark.png", 1024, transparent],
]) {
  const image = new Resvg(source, {
    fitTo: { mode: "width", value: size },
    font: { loadSystemFonts: false },
  }).render();
  await writeFile(new URL(name, publicDir), image.asPng());
}

console.log("Generated the Bonjou SVG, PNG, avatar, and browser icons.");
